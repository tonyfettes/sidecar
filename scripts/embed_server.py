#!/usr/bin/env python3
"""Gzip-compress cross-compiled binaries and generate a MoonBit embedding module.

Default usage (from repo root, after `cd server && zig build dist`):
    python3 scripts/embed_server.py

Reusable for downstream plugins:
    python3 scripts/embed_server.py \\
        --dist-dir path/to/dist \\
        --out embedded_plugin.generated.mbt \\
        --map-name embedded_plugins \\
        --type-prefix @sidecar.
"""

import argparse
import gzip
import hashlib
from pathlib import Path


def bytes_literal(data: bytes) -> str:
    # Multi-line Bytes array literal (64 bytes/line) to stay well within
    # MoonBit's column limit while remaining a compile-time constant.
    chunks = []
    for i in range(0, len(data), 64):
        chunk = data[i : i + 64]
        chunks.append("  " + ", ".join(f"0x{b:02x}" for b in chunk) + ",")
    return "[\n" + "\n".join(chunks) + "\n]"


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--dist-dir", default="server/zig-out/dist")
    ap.add_argument("--out", default="embedded_server.generated.mbt")
    ap.add_argument("--map-name", default="embedded_servers")
    ap.add_argument("--type-prefix", default="")
    ap.add_argument("--public", action="store_true")
    args = ap.parse_args()

    dist_dir = Path(args.dist_dir)
    if not dist_dir.is_dir():
        raise SystemExit(f"dist directory not found: {dist_dir}")

    entries: list[tuple[str, str, str, bytes, int]] = []
    for plat_dir in sorted(p for p in dist_dir.iterdir() if p.is_dir()):
        files = sorted(f for f in plat_dir.iterdir() if f.is_file())
        if not files:
            continue
        if len(files) != 1:
            raise SystemExit(f"expected 1 artifact in {plat_dir}, found {len(files)}")
        art = files[0]
        raw = art.read_bytes()
        sha = hashlib.sha256(raw).hexdigest()
        gz = gzip.compress(raw, compresslevel=9, mtime=0)
        entries.append((plat_dir.name, art.name, sha, gz, len(raw)))

    if not entries:
        raise SystemExit(f"no platform artifacts found under {dist_dir}")

    vis = "pub " if args.public else ""
    t = f"{args.type_prefix}EmbeddedArtifact"
    lines: list[str] = [
        "///|",
        f"/// Generated by `scripts/embed_server.py` from `{args.dist_dir}`.",
        "/// Do not edit by hand.",
        f"{vis}let {args.map_name} : Map[String, {t}] = {{",
    ]

    total_raw = 0
    total_gz = 0
    for plat, filename, sha, gz, raw_len in entries:
        total_raw += raw_len
        total_gz += len(gz)
        ident = f"{args.map_name}_{plat.replace('-', '_')}_gz"
        lines.append(
            f'  "{plat}": {t}::new(filename="{filename}", sha256="{sha}", gzip_bytes={ident}),'
        )
    lines.append("}")
    lines.append("")

    for plat, filename, sha, gz, raw_len in entries:
        ident = f"{args.map_name}_{plat.replace('-', '_')}_gz"
        lines.append("///|")
        lines.append(
            f"// {plat}/{filename}: raw={raw_len} bytes, gzip={len(gz)} bytes, sha256={sha[:16]}"
        )
        lines.append(f"let {ident} : Bytes = {bytes_literal(gz)}")
        lines.append("")

    out_path = Path(args.out)
    out_path.write_text("\n".join(lines), encoding="utf-8")

    print(f"Generated {out_path} ({len(entries)} platforms):")
    for plat, filename, sha, gz, raw_len in entries:
        ratio = (len(gz) / raw_len) * 100.0 if raw_len else 0.0
        print(
            f"  {plat:16s} {filename:20s} raw={raw_len:7d}B  gzip={len(gz):6d}B ({ratio:4.1f}%)  sha256={sha[:12]}"
        )
    print(f"  TOTAL: raw={total_raw}B ({total_raw/1024:.1f} KiB) -> gzip={total_gz}B ({total_gz/1024:.1f} KiB)")


if __name__ == "__main__":
    main()
